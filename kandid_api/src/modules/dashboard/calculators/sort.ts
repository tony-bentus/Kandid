/** Comparação de strings independente de locale (CLI e navegador concordam). */
export function compareStrings(left: string, right: string): number {
  if (left < right) {
    return -1;
  }
  if (left > right) {
    return 1;
  }
  return 0;
}

/** `null` vem primeiro, seguindo a ordenação ASC do MySQL. */
export function compareNullableStrings(
  left: string | null,
  right: string | null,
): number {
  if (left === right) {
    return 0;
  }
  if (left === null) {
    return -1;
  }
  if (right === null) {
    return 1;
  }
  return compareStrings(left, right);
}
